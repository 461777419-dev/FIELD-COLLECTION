const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const sharp=require('sharp');

test('画板、图库与目录按编号对应；共享原图硬链接、重名、改名、删除归档与重开',async()=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'atlas-board-links-'));
  process.env.REFERENCE_BOARD_DATA_DIR=dir;
  let server;
  const start=async()=>{delete require.cache[require.resolve('../server')];server=require('../server').server;await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));return `http://127.0.0.1:${server.address().port}`;};
  try{
    let base=await start();
    const api=async(route,method='GET',body)=>{const r=await fetch(base+route,{method,headers:{'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});const value=await r.json();assert.ok(r.ok,JSON.stringify(value));return value;};
    const folder=await api('/api/folders','POST',{name:'同名'});
    let catalog=await api('/api/board/catalog');
    const galleryBoardId=catalog.links.find(link=>link.folderId===folder.id).boardId;
    const board={id:'board-test',name:'同名',elements:[],operationHistory:[],operationHistoryIndex:-1,panOffset:{x:12,y:24},zoom:1.2,canvasBackgroundColor:'#fff8fb'};
    catalog=await api('/api/board/catalog','POST',{boards:[board]});
    const link=catalog.links.find(link=>link.boardId===board.id);
    assert.notEqual(link.folderId,folder.id,'同名不误绑定');
    assert.notEqual(link.directory,catalog.links.find(link=>link.folderId===folder.id).directory,'磁盘名称冲突安全处理');
    const png=await sharp({create:{width:8,height:7,channels:3,background:'#e04080'}}).png().toBuffer();
    const image=await fetch(base+'/api/images',{method:'POST',headers:{'Content-Type':'image/png','X-File-Name':'test.png','X-Folder-Id':folder.id},body:png}).then(r=>r.json());
    board.elements=[{id:'image-element',type:'image',href:'/preview/'+image.id,originalHref:'/media/'+image.id,x:23,y:45,width:8,height:7,mimeType:'image/png',grayscale:true}];
    const galleryBoard={...board,id:galleryBoardId,name:folder.name,elements:[]};
    await api('/api/board/document','PUT',{boards:[board,galleryBoard],activeBoardId:board.id});
    const alias=path.join(dir,'media',link.directory,`atlas-${image.id}.png`),original=path.join(dir,'media',image.storagePath);
    assert.equal(fs.statSync(alias).ino,fs.statSync(original).ino,'共享素材使用硬链接而非复制');
    assert.ok(fs.existsSync(path.join(dir,'media',link.directory,'.画板.json')));
    assert.ok(fs.existsSync(path.join(dir,'backup-before-board-links','library.json')));
    const library=await api('/api/state');
    assert.ok(library.folders.find(item=>item.id===link.folderId).referenceIds.includes(image.id));
    await api('/api/folders/'+link.folderId,'PATCH',{name:'图库改名'});
    let doc=await api('/api/board/document');
    assert.equal(doc.boards.find(item=>item.id===board.id).name,'图库改名');
    assert.equal((await api('/api/board/document')).boards.find(item=>item.id===board.id).name,'图库改名','重读不回滚改名');
    const updated=doc.boards.find(item=>item.id===board.id);updated.name='画板改名';
    await api('/api/board/catalog','POST',{boards:[updated]});
    assert.equal((await api('/api/state')).folders.find(item=>item.id===link.folderId).name,'画板改名');
    const oldSourceUrl='/board-media/'+require('node:crypto').createHash('sha256').update(png).digest('hex')+'.png';
    await fetch(base+'/api/board/media',{method:'POST',headers:{'Content-Type':'image/png'},body:png});
    updated.elements.push({...board.elements[0],id:'generated',href:oldSourceUrl,originalHref:undefined});
    await api('/api/board/document','PUT',{boards:[updated,galleryBoard],activeBoardId:board.id});
    assert.equal((await api('/api/state')).images.length,1,'画板媒体按内容去重');
    assert.equal(fs.statSync(path.join(dir,'board','media',path.basename(oldSourceUrl))).ino,fs.statSync(path.join(dir,'media',(await api('/api/state')).images[0].storagePath)).ino,'已有图库图与画板媒体共享磁盘数据');
    await new Promise(resolve=>server.close(resolve));base=await start();
    doc=await api('/api/board/document');
    assert.equal(doc.boards.find(item=>item.id===board.id).elements[0].grayscale,true);
    assert.equal(doc.boards.find(item=>item.id===board.id).elements[0].x,23,'同步不改布局');
    const backup=await (await fetch(base+'/api/backup')).arrayBuffer();
    const restored=await fetch(base+'/api/backup/restore',{method:'POST',body:backup});
    assert.equal(restored.status,200,await restored.text());
    await api('/api/folders/'+link.folderId,'DELETE');
    doc=await api('/api/board/document');assert.ok(!doc.boards.some(item=>item.id===board.id));
    assert.ok(fs.readdirSync(path.join(dir,'board','archive')).length>0);
    assert.deepEqual(Buffer.from(await (await fetch(base+'/media/'+image.id)).arrayBuffer()),png,'删关联文件夹不删原图');
    assert.equal(fs.existsSync(path.join(dir,'media','画板改名')),false,'只清理由系统创建的目录文件');
    await api('/api/board/document','PUT',{boards:[galleryBoard],activeBoardId:galleryBoard.id});
    const disposable={...board,id:'disposable-board',name:'可删画板',elements:[]};
    await api('/api/board/document','PUT',{boards:[galleryBoard,disposable],activeBoardId:galleryBoard.id});
    const disposableLink=(await api('/api/board/catalog')).links.find(link=>link.boardId===disposable.id);
    await api('/api/board/document','PUT',{boards:[galleryBoard],activeBoardId:galleryBoard.id});
    assert.ok((await api('/api/state')).folders.some(folder=>folder.id===disposableLink.folderId),'删除画板保留图库文件夹');
    assert.ok(!(await api('/api/board/document')).boards.some(board=>board.id===disposable.id),'归档画板不自动复活');
  }finally{if(server?.listening)await new Promise(resolve=>server.close(resolve));fs.rmSync(dir,{recursive:true,force:true});}
});
