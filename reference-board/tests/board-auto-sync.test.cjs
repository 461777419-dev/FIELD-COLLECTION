const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const sharp=require('sharp');

test('素材自动双向同步：初次平铺、保留布局、去重、共享删除确认、回收站与恢复',async()=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'atlas-auto-sync-'));
  process.env.REFERENCE_BOARD_DATA_DIR=dir;
  const {server}=require('../server');await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const base=`http://127.0.0.1:${server.address().port}`;
  const api=async(route,method='GET',body,headers={})=>{const r=await fetch(base+route,{method,headers:{'Content-Type':'application/json',...headers},body:body===undefined?undefined:JSON.stringify(body)});const result=await r.json();assert.ok(r.ok,JSON.stringify(result));return result;};
  const upload=async(folderId,color)=>{const bytes=await sharp({create:{width:400,height:300,channels:3,background:color}}).png().toBuffer();const r=await fetch(base+'/api/images',{method:'POST',headers:{'Content-Type':'image/png','X-File-Name':'test.png','X-Folder-Id':folderId},body:bytes});assert.equal(r.status,201);return {image:await r.json(),bytes};};
  const sync=boards=>api('/api/board/sync','POST',{boards,activeBoardId:boards[0].id});
  try{
    const folder=await api('/api/folders','POST',{name:'自动同步'});
    const a=await upload(folder.id,'#de4380'),b=await upload(folder.id,'#56a590');
    let doc=await api('/api/board/document');
    let result=await sync(doc.boards),board=result.boards[0];
    assert.equal(board.elements.length,2);assert.ok(Math.abs(board.elements[0].x-board.elements[1].x)>=400,'首次网格排布');
    assert.ok(result.fitBoardIds.includes(board.id));
    board.operationHistory=[{id:'saved-history',elements:board.elements}];board.operationHistoryIndex=0;
    await api('/api/board/document','PUT',{boards:[board],activeBoardId:board.id});
    board.elements[0].x=1234;board.elements[0].y=-410;
    result=await sync([{...board,operationHistory:[],operationHistoryIndex:-1}]);assert.equal(result.boards[0].elements[0].x,1234);assert.equal(result.boards[0].operationHistory[0].id,'saved-history','自动同步不清空已保存的撤销历史');
    result=await sync(result.boards);assert.equal(result.boards[0].elements.length,2,'反复自动同步不重复');assert.deepEqual(result.fitBoardIds,[]);
    assert.equal((await api('/api/board/revision')).revision,result.revision,'空闲检查使用同一版本标识');
    const unchangedRevision=result.revision;
    result=await sync(result.boards);assert.equal(result.revision,unchangedRevision,'无变化不重写工程或图库');
    const c=await upload(folder.id,'#dfa830');
    assert.notEqual((await api('/api/board/revision')).revision,unchangedRevision,'图库新增会使版本标识改变');
    result=await sync(result.boards);board=result.boards[0];assert.equal(board.elements.length,3);assert.equal(board.elements[0].y,-410,'后续新增不打乱布局');
    const generated=await sharp({create:{width:60,height:50,channels:3,background:'#7341da'}}).png().toBuffer();
    const media=await fetch(base+'/api/board/media',{method:'POST',headers:{'Content-Type':'image/png'},body:generated}).then(r=>r.json());
    board.elements.push({id:'dragged',type:'image',href:media.url,x:400,y:600,width:60,height:50,mimeType:'image/png'});
    result=await sync([board]);board=result.boards[0];
    const library=await api('/api/state'),added=library.images.find(image=>image.id===board.elements.find(element=>element.id==='dragged').atlasImageId);
    assert.ok(added);assert.equal(added.folderId,folder.id,'拖进画板的素材自动入对应图库文件夹');
    assert.equal(fs.statSync(path.join(dir,'board','media',path.basename(media.url))).ino,fs.statSync(path.join(dir,'media',added.storagePath)).ino,'没有额外一份原图');
    const other={...board,id:'other-board',name:'第二画板',elements:[{...board.elements[0],id:'other-reference'}]};
    result=await sync([board,other]);board=result.boards.find(item=>item.id===board.id);
    const target=board.elements[0],targetId=target.atlasImageId;
    const removed={...board,elements:board.elements.filter(element=>element.id!==target.id)};
    let pending=await sync([removed,result.boards.find(item=>item.id===other.id)]);
    assert.ok(pending.needsConfirmation);assert.equal((await api('/api/state')).trash.length,0,'确认前不删除');
    assert.ok(pending.affected.some(item=>item.id===other.id));
    result=await api('/api/board/sync','POST',{boards:[removed,result.boards.find(item=>item.id===other.id)],confirmedDeleteIds:pending.deleteIds});
    assert.ok(result.boards.every(item=>!item.elements.some(element=>element.atlasImageId===targetId)));
    assert.ok((await api('/api/state')).trash.some(image=>image.id===targetId));
    result=await sync(result.boards);assert.ok((await api('/api/state')).trash.some(image=>image.id===targetId),'轮询不自动复活回收站图片');
    const undo=result.boards.find(item=>item.id===board.id);undo.elements.push(target);
    result=await sync(result.boards);assert.ok((await api('/api/state')).images.some(image=>image.id===targetId),'画板撤销删除会恢复原素材');
    const preflight=await fetch(base+'/api/images/'+targetId,{method:'DELETE'});assert.equal(preflight.status,409,'图库删除也提示画板影响');
    await api('/api/images/'+targetId,'DELETE',undefined,{'X-Confirm-Board-Delete':'1'});
    result=await sync(result.boards);assert.ok(result.boards.every(item=>!item.elements.some(element=>element.atlasImageId===targetId)),'图库删除传播到所有画板');
    await api('/api/trash/'+targetId+'/restore','POST');
    result=await sync(result.boards);assert.equal(result.boards.find(item=>item.id===board.id).elements.find(element=>element.id===target.id).x,1234,'回收站恢复保留画板布局');
    const restarted=await api('/api/board/document');assert.equal(restarted.boards.find(item=>item.id===board.id).elements.length,4);
    assert.ok(fs.existsSync(path.join(dir,'media',folder.diskName,'.画板.json')));
    const stale=result.boards;
    await api('/api/images/'+added.id,'DELETE',undefined,{'X-Confirm-Board-Delete':'1'});
    await api('/api/trash/'+added.id+'/delete','POST');
    result=await sync(stale);
    assert.ok(!(await api('/api/state')).images.some(image=>image.contentHash===added.contentHash),'彻底删除后旧画板媒体地址不复活素材');
    result=await api('/api/board/sync','POST',{boards:result.boards.filter(item=>item.id!==other.id),deletedBoardIds:[other.id]});
    assert.ok(!result.boards.some(item=>item.id===other.id),'自动同步不复活已删除画板');
  }finally{await new Promise(resolve=>server.close(resolve));fs.rmSync(dir,{recursive:true,force:true});}
});

test('自动同步响应合并保留请求期间的移动、删除与撤销历史',()=>{
  const ts=require('../../artflow-integrated/node_modules/typescript');
  const Module=require('node:module');
  const filename=path.resolve(__dirname,'../../artflow-integrated/utils/atlas-sync.ts');
  const compiled=ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
  const m=new Module(filename);m._compile(compiled,filename);
  const {mergeAtlasSync}=m.exports;
  const element={id:'a',type:'image',href:'blob:source',x:0,y:0,width:100,height:100};
  const sent=[{id:'board',name:'画板',elements:[element],operationHistory:['original']}];
  const current=[{...sent[0],elements:[{...element,x:800}],operationHistory:['original','move']}];
  const remote=[{...sent[0],elements:[{...element,href:'/media/id',atlasImageId:'id'},{...element,id:'b',x:400}]}];
  const merged=mergeAtlasSync(current,sent,remote);
  assert.equal(merged[0].elements[0].x,800);assert.equal(merged[0].elements[0].href,'/media/id');assert.deepEqual(merged[0].operationHistory,['original','move']);
  assert.equal(merged[0].elements.length,2);
  assert.equal(mergeAtlasSync([{...current[0],elements:[]}],sent,remote)[0].elements.some(element=>element.id==='a'),false,'不补回请求期间用户删除的卡片');
});
