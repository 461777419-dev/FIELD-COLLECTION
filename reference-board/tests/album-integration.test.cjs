const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const sharp = require('sharp');

test('浅蓝相册资源可离线读取，导入原图与编辑信息在重新加载后保留', async () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'album-integration-'));
  process.env.REFERENCE_BOARD_DATA_DIR = directory;
  let server;
  async function start() {
    delete require.cache[require.resolve('../server')];
    server = require('../server').server;
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    return `http://127.0.0.1:${server.address().port}`;
  }
  try {
    let base = await start();
    const aiSettings={provider:'custom',model:'vision-model',generationModel:'image-model',imageProtocol:'chat',name:'测试接口',address:'https://example.com/v1'};
    const aiSaved=await fetch(base+'/api/ai/settings',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(aiSettings)});
    assert.equal(aiSaved.status,200);
    const shared=await fetch(base+'/api/ai/settings').then(r=>r.json());
    assert.equal(shared.models.custom,'vision-model');assert.equal(shared.generationModels.custom,'image-model');assert.equal(shared.imageProtocol,'chat');assert.equal(shared.key,undefined);
    const noKey=await fetch(base+'/api/ai/board',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({prompt:'test'})});
    assert.equal(noKey.status,400);assert.match((await noKey.json()).error,/API Key/);
    for (const asset of ['/assets/whale-album.png', '/assets/all-images.png', '/assets/related-images.png', '/album.css', '/album.js', '/whale.css', '/wave.css', '/whale.js', '/attribution.html', '/assets/app-icon.png', '/assets/observation-note.svg', '/assets/whale/maid-sleepy.png', '/assets/whale/maid-determined.png', '/assets/whale/maid-delighted.png', '/assets/whale/maid-NOTICE', '/assets/whale/maid-LICENSE-ARTWORK']) {
      const response = await fetch(base + asset);
      assert.equal(response.status, 200, asset);
      assert.ok((await response.arrayBuffer()).byteLength > 0, asset);
    }
    const folderResponse = await fetch(base + '/api/folders', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ name: '测试目录' }) });
    const folder = await folderResponse.json();
    const bytes = await sharp({ create: { width: 48, height: 81, channels: 3, background: '#95b6dc' } }).png().toBuffer();
    const response = await fetch(base + '/api/images', { method: 'POST', headers: { 'Content-Type': 'image/png', 'X-File-Name': encodeURIComponent('蓝色观察.png'), 'X-Folder-Id': folder.id }, body: bytes });
    assert.equal(response.status, 201);
    const image = await response.json();
    assert.equal(image.width, 48); assert.equal(image.height, 81);
    assert.equal(image.hasPreview, true);
    assert.equal(fs.readdirSync(path.join(directory, 'cache', 'previews')).length, 0, '小图直接复用原图');
    const colored = await fetch(base + '/api/folders/' + folder.id, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ color: '#c582ae' }) }).then(r => r.json());
    assert.equal(colored.color, '#c582ae');
    const legacyPreview = path.join(directory, 'media', path.dirname(image.storagePath), image.id + '.preview.png');
    fs.writeFileSync(legacyPreview, bytes);
    const patch = await fetch(base + '/api/images/' + image.id, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ tags: ['手绘'], note: '原比例保留', favorite: true }) });
    assert.equal(patch.status, 200);
    await new Promise(resolve => server.close(resolve));
    base = await start();
    const saved = await fetch(base + '/api/state').then(response => response.json());
    assert.equal(saved.images.length, 1);
    assert.equal(saved.images[0].folderId, folder.id);
    assert.equal(saved.images[0].note, '原比例保留');
    assert.deepEqual(saved.images[0].tags, ['手绘']);
    assert.equal(saved.images[0].favorite, true);
    assert.equal(saved.folders.find(f => f.id === folder.id).color, '#c582ae');
    assert.equal(fs.existsSync(legacyPreview), false, '旧预览从原图目录迁出');
    assert.deepEqual(fs.readFileSync(path.join(directory, 'cache', 'previews', image.id + '.preview.png')), bytes);
    assert.deepEqual(Buffer.from(await (await fetch(base + '/preview/' + image.id)).arrayBuffer()), bytes);
    assert.deepEqual(Buffer.from(await (await fetch(base + '/media/' + image.id)).arrayBuffer()), bytes);
    const tag = await fetch(base + '/api/tags', { method:'POST', headers:{'Content-Type':'application/json'}, body:JSON.stringify({name:'海蓝',color:'#4599cc'}) }).then(r=>r.json());
    const edited = await fetch(base + '/api/tags/' + encodeURIComponent(tag.key), { method:'PATCH', headers:{'Content-Type':'application/json'}, body:JSON.stringify({name:tag.name,color:'#dd8855'}) }).then(r=>r.json());
    assert.equal(edited.tags.find(t=>t.key===tag.key).color, '#dd8855');
    const videoBytes = fs.readFileSync(path.join(__dirname,'fixtures','playback.webm'));
    const imported = await fetch(base + '/api/images', { method:'POST', headers:{'Content-Type':'video/webm','X-File-Name':'sample.webm'},body:videoBytes });
    assert.equal(imported.status,201);
    const video = await imported.json();
    assert.equal(video.hasPreview,false);
    const segment = await fetch(base + '/media/' + video.id, {headers:{Range:'bytes=4-11'}});
    assert.equal(segment.status,206); assert.equal(segment.headers.get('content-type'),'video/webm');
    assert.deepEqual(Buffer.from(await segment.arrayBuffer()),videoBytes.subarray(4,12));
    const suffix = await fetch(base + '/media/' + video.id,{headers:{Range:'bytes=-4'}});
    assert.deepEqual(Buffer.from(await suffix.arrayBuffer()),videoBytes.subarray(-4));
    assert.equal((await fetch(base + '/media/' + video.id,{headers:{Range:'bytes=999-'}})).status,416);
    assert.equal((await fetch(base + '/media/' + video.id,{method:'HEAD'})).headers.get('content-length'),String(videoBytes.length));
    const invalid = await fetch(base + '/api/images', { method: 'POST', headers: { 'Content-Type': 'image/png', 'X-File-Name': 'bad.png' }, body: 'invalid' });
    assert.equal(invalid.status, 422);
    assert.equal((await fetch(base + '/api/state').then(response => response.json())).images.length, 2);
    const parentFolder = await fetch(base + '/api/folders', { method:'POST', headers:{'Content-Type':'application/json'}, body:JSON.stringify({name:'父目录',color:'#336699'}) }).then(r=>r.json());
    assert.equal(parentFolder.color, '#336699');
    const reparent = await fetch(base + '/api/folders/' + folder.id, { method:'PATCH', headers:{'Content-Type':'application/json'}, body:JSON.stringify({parentId:parentFolder.id}) });
    assert.equal(reparent.status, 200);
    assert.equal((await reparent.json()).parentId, parentFolder.id);
    assert.equal(fs.existsSync(path.join(directory, 'media', parentFolder.diskName, folder.diskName)), true);
    assert.deepEqual(Buffer.from(await (await fetch(base + '/media/' + image.id)).arrayBuffer()), bytes);
    const cycle = await fetch(base + '/api/folders/' + parentFolder.id, { method:'PATCH', headers:{'Content-Type':'application/json'}, body:JSON.stringify({parentId:folder.id}) });
    assert.equal(cycle.status, 400);
    const rootMove = await fetch(base + '/api/folders/' + folder.id, { method:'PATCH', headers:{'Content-Type':'application/json'}, body:JSON.stringify({parentId:null}) });
    assert.equal(rootMove.status, 200);
    assert.equal(fs.existsSync(path.join(directory, 'media', folder.diskName)), true);
    const largeBytes = await sharp({ create: { width: 1900, height: 100, channels: 3, background: '#cc6744' } }).png().toBuffer();
    const largeResponse = await fetch(base + '/api/images', { method: 'POST', headers: { 'Content-Type': 'image/png', 'X-File-Name': 'large.png', 'X-Duplicate-Action': 'keep' }, body: largeBytes });
    assert.equal(largeResponse.status, 201);
    const large = await largeResponse.json();
    const cachedLarge = path.join(directory, 'cache', 'previews', large.id + '.preview.png');
    assert.equal(fs.existsSync(cachedLarge), true, '大图预览放入缓存');
    const converted = await fetch(base + '/api/images/' + image.id + '/convert', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ format: 'webp' }) });
    assert.equal(converted.status, 201);
    const document = {boards:[{id:'board-test',name:'灵感画板',elements:[{id:'reference',type:'image',href:'/preview/'+image.id,originalHref:'/media/'+image.id,x:10,y:20,width:48,height:81}],panOffset:{x:123,y:77},zoom:1.25,operationHistory:[],operationHistoryIndex:-1}],activeBoardId:'board-test'};
    const saveBoard = await fetch(base+'/api/board/document',{method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify(document)});
    assert.equal(saveBoard.status,200);
    const reopened = await fetch(base+'/api/board/document').then(r=>r.json());
    assert.equal(reopened.boards[0].zoom,1.25);assert.equal(reopened.boards[0].elements[0].originalHref,'/media/'+image.id);
    assert.equal(fs.readdirSync(path.join(directory,'board','media')).length,0,'图库引用不重复保存素材');
    const uploaded = await fetch(base+'/api/board/media',{method:'POST',headers:{'Content-Type':'image/png'},body:bytes}).then(r=>r.json());
    assert.deepEqual(Buffer.from(await(await fetch(base+uploaded.url)).arrayBuffer()),bytes);
    await fetch(base+'/api/board/media',{method:'POST',headers:{'Content-Type':'image/png'},body:bytes});
    assert.equal(fs.readdirSync(path.join(directory,'board','media')).length,1,'画板导入素材按内容去重');
    assert.equal((await fetch(base+'/api/board/document',{method:'PUT',headers:{'Content-Type':'application/json'},body:'{"boards":[]}'})).status,400);
    const backup = Buffer.from(await (await fetch(base + '/api/backup')).arrayBuffer());
    const restored = await fetch(base + '/api/backup/restore', { method: 'POST', body: backup });
    assert.equal(restored.status, 200, await restored.text());
    assert.equal(fs.existsSync(cachedLarge), true, '备份恢复保留独立预览缓存');
    assert.equal((await fetch(base+'/api/board/document').then(r=>r.json())).activeBoardId,'board-test','备份恢复包含画板工程');
    assert.deepEqual(Buffer.from(await (await fetch(base + '/media/' + image.id)).arrayBuffer()), bytes);
  } finally {
    if (server?.listening) await new Promise(resolve => server.close(resolve));
    fs.rmSync(directory, { recursive: true, force: true });
  }
});
