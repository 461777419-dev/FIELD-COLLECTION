require('./register-typescript.cjs');
const assert=require('node:assert/strict');
const {presentationElements}=require('../utils/presentation-import.ts');
const {serializeProjectDocument,deserializeProjectDocument}=require('../utils/projectDocument.ts');
const {commitCanvasOperation,applyCanvasOperation}=require('../utils/operationHistory.ts');
const page={href:'data:image/png;base64,aA==',width:1600,height:900};
const elements=presentationElements('Deck',[page,page],{x:20,y:30});
const frames=elements.filter(el=>el.type==='frame').reverse();
assert.deepEqual(frames.map(frame=>frame.name),['Deck · 1','Deck · 2']);
assert.ok(frames[1].y>frames[0].y);
assert.ok(elements.filter(el=>el.type==='image').every(image=>frames.some(frame=>frame.id===image.parentId&&frame.width===image.width&&frame.height===image.height)));
const history=commitCanvasOperation([],-1,[],elements);
assert.deepEqual(applyCanvasOperation(elements,history.operationHistory[0],'undo'),[]);
const board={id:'deck',name:'Deck',elements,...history,zoom:1,panOffset:{x:0,y:0},canvasBackgroundColor:'#fff'};
assert.deepEqual(deserializeProjectDocument(JSON.parse(JSON.stringify(serializeProjectDocument([board]))))[0].elements.map(({assetId,...element})=>element),elements);
assert.throws(()=>presentationElements('bad',[{...page,width:0}],{x:0,y:0}));
const storedPage={...page,href:'/board-media/'+'a'.repeat(64)+'.png'};
assert.ok(presentationElements('stored',[storedPage],{x:0,y:0}).some(element=>element.type==='image'&&element.href===storedPage.href));
assert.throws(()=>presentationElements('unsafe',[{...page,href:'/board-media/../../secret'}],{x:0,y:0}));
console.log('PPT import: slide order, aspect ratio, frame/image parenting, undo and project roundtrip passed');
